QUESTIONS_BY_ID: dict[str, PQuestion] = {q.id: q for q in PERSONALITY_QUESTIONS}
_OPTIONS_BY_ID: dict[str, POption] = {
    o.id: o for q in PERSONALITY_QUESTIONS for o in q.options
}

# Порядок разрешения ничьей — по частоте появления в каталоге (реже — выше).
_TIE_ORDER = ["inspirer", "romantic", "strategist", "keeper", "seeker", "harmonizer"]


def compute_archetype(answers: dict[str, str]) -> tuple[str, dict[str, int]]:
    """Вернуть (ключ типажа, баллы). answers: question_id -> option_id."""
    scores: dict[str, int] = {k: 0 for k in ARCHETYPES}
    for qid, oid in answers.items():
        opt = _OPTIONS_BY_ID.get(oid)
        if opt is None or not oid.startswith(qid):
            raise ValueError(f"invalid option {oid} for question {qid}")
        scores[opt.archetype] += 1
    winner = max(
        scores,
        key=lambda k: (scores[k], -_TIE_ORDER.index(k)),
    )
    return winner, scores

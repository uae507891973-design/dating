@dataclass(frozen=True)
class POption:
    id: str
    label: str
    archetype: str


@dataclass(frozen=True)
class PQuestion:
    id: str
    text: str
    options: tuple[POption, ...]


def _q(qid: str, text: str, *opts: tuple[str, str]) -> PQuestion:
    return PQuestion(
        id=qid,
        text=text,
        options=tuple(
            POption(id=f"{qid}_{i}", label=label, archetype=arch)
            for i, (label, arch) in enumerate(opts, start=1)
        ),
    )


